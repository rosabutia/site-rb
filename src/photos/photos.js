const assets = import.meta.glob("../images/galeria/*.jpg", {
  eager: true,
  import: "default",
  query: "?url",
});

function img(file) {
  const match = Object.entries(assets).find(([key]) => key.endsWith(`/${file}`));
  if (!match) throw new Error(`Imagem não encontrada: ${file}`);
  return match[1];
}

